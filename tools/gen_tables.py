#!/usr/bin/env python3
"""Generate components/namemap/tables_gen.c from Unicode 16.0.0 Unihan + UnicodeData.

Usage: tools/gen_tables.py <download-dir>
Data is under the Unicode License v3 (licenses/Unicode-3.0.txt). No GPL tables.
"""
import io, sys, unicodedata, urllib.request, zipfile, pathlib
VER = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VER}/ucd/"
HAN0, HAN1 = 0x4E00, 0x9FFF
out_dir = pathlib.Path(__file__).resolve().parent.parent / "components/namemap"

def fetch(dl, name):
    p = pathlib.Path(dl) / name
    if not p.exists():
        p.write_bytes(urllib.request.urlopen(BASE + name).read())
    return p.read_bytes()

def strip_tone(s):
    d = unicodedata.normalize("NFD", s).replace("u\u0308", "v").replace("U\u0308", "V")   # ü/ǘ... -> v
    return "".join(c for c in d if not unicodedata.combining(c)).upper()

def main(dl):
    z = zipfile.ZipFile(io.BytesIO(fetch(dl, "Unihan.zip")))
    fields = {"kMandarin": {}, "kHangul": {}, "kJapanese": {}}
    for line in z.read("Unihan_Readings.txt").decode("utf-8").splitlines():
        if not line.startswith("U+"):
            continue
        cp, field, val = line.split("\t", 2)
        if field in fields:
            fields[field][int(cp[2:], 16)] = val.split()[0]
    pool, index, size = ["\0"], {"": 0}, [1]
    def intern(s):
        if s not in index:
            index[s] = size[0]
            pool.append(s + "\0")
            size[0] += len(s.encode()) + 1
        return index[s]
    mand, hang, jap = [], [], []
    for cp in range(HAN0, HAN1 + 1):
        m = fields["kMandarin"].get(cp)
        mand.append(intern(strip_tone(m)) if m else 0)
        h = fields["kHangul"].get(cp)
        hang.append(ord(h.split(":")[0][0]) if h else 0)
        j = fields["kJapanese"].get(cp)
        jap.append(intern(j) if j else 0)
    blob = "".join(pool).encode()
    assert len(blob) < 65536, "pool must fit uint16 offsets"
    fold = []
    for rng in (range(0xC0, 0x250), range(0x1E00, 0x1F00)):
        for cp in rng:
            d = "".join(c for c in unicodedata.normalize("NFKD", chr(cp)) if c.isascii() and c.isalpha())
            special = {"ß": "SS", "ẞ": "SS", "Æ": "AE", "æ": "AE", "Œ": "OE", "œ": "OE", "Ø": "O", "ø": "O", "Đ": "D", "đ": "D",
                       "Ł": "L", "ł": "L", "Þ": "TH", "þ": "TH", "Ð": "D", "ð": "D", "ı": "I", "Ħ": "H", "ħ": "H"}
            fold.append(special.get(chr(cp), d.upper()[:2]))
    def arr(name, vals, t):
        rows = ",".join(str(v) for v in vals)
        return f"const {t} {name}[{len(vals)}] = {{{rows}}};\n"
    src = ["/* GENERATED by tools/gen_tables.py from Unicode " + VER + " (Unicode License v3). Do not edit. */\n",
           "#include <stdint.h>\n",
           arr("nm_han_mandarin", mand, "uint16_t"), arr("nm_han_hangul", hang, "uint16_t"), arr("nm_han_japanese", jap, "uint16_t"),
           "const char nm_pool[" + str(len(blob)) + "] = {" + ",".join(str(b) for b in blob) + "};\n",
           "const char nm_latin_fold[" + str(len(fold)) + "][3] = {" + ",".join('"' + f + '"' for f in fold) + "};\n"]
    (out_dir / "tables_gen.c").write_text("".join(src))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp")
